"""F18 - walk ``runs/``, join on config, emit results tables and IEEE LaTeX.

Every number in the paper is generated by this, never typed. The reproducibility check's
acceptance test is that a clean clone reproduces a headline table from
``repro.sh`` alone, which is only possible if nothing is transcribed by hand.

Seed handling is the part that matters: headline rows report mean +/- std over
three seeds, and a row backed by one seed is LABELLED as such in the
table caption rather than silently presented as if it were the same quality of
evidence.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from ddetect.utils.log import get_logger, setup_logging

log = get_logger(__name__)


def collect_runs(run_root: str | Path = "runs") -> pd.DataFrame:
    """One row per (experiment, seed, test split)."""
    rows: list[dict[str, Any]] = []
    for metrics_p in sorted(Path(run_root).glob("*/seed*/metrics_report.json")):
        run_dir = metrics_p.parent
        exp = run_dir.parent.name
        seed = int(run_dir.name.replace("seed", ""))

        stamp: dict[str, Any] = {}
        if (run_dir / "stamp.json").exists():
            stamp = json.loads((run_dir / "stamp.json").read_text())
        cal: dict[str, Any] = {}
        if (run_dir / "calibration.json").exists():
            cal = json.loads((run_dir / "calibration.json").read_text())

        for name, rep in json.loads(metrics_p.read_text()).items():
            rows.append(
                {
                    "exp": exp,
                    "seed": seed,
                    "split": name,
                    "is_breakdown": "/" in name,
                    "git_sha": stamp.get("git_sha", "?"),
                    "config_hash": stamp.get("config_hash", "?"),
                    "calibration_degenerate": cal.get("degenerate", None),
                    "run_dir": str(run_dir),
                    **{k: v for k, v in rep.items() if k != "confusion"},
                }
            )
    if not rows:
        log.warning("no metrics_report.json found under %s -- run ddetect.evaluate first", run_root)
    return pd.DataFrame(rows)


def aggregate_seeds(
    df: pd.DataFrame, metrics: tuple[str, ...] = ("auc", "accuracy", "f1", "eer", "ece")
) -> pd.DataFrame:
    """Collapse seeds into mean +/- std, keeping the seed count visible."""
    if df.empty:
        return df
    base = df[~df.is_breakdown]
    agg = (
        base.groupby(["exp", "split"])
        .agg(
            n_seeds=("seed", "nunique"),
            n=("n", "first"),
            **{f"{m}_mean": (m, "mean") for m in metrics},
            **{f"{m}_std": (m, "std") for m in metrics},
        )
        .reset_index()
    )
    # A single-seed std is NaN, not 0: pandas is right, and writing 0 would
    # claim a precision we did not measure.
    agg["single_seed"] = agg.n_seeds < 2
    return agg


def cross_dataset_table(agg: pd.DataFrame, in_split: str = "val") -> pd.DataFrame:
    """The headline table: in-dataset vs cross-dataset AUC, and the gap."""
    if agg.empty:
        return agg
    rows = []
    for exp, g in agg.groupby("exp"):
        base = g[g.split == in_split]
        if base.empty:
            continue
        in_auc = float(base.auc_mean.iloc[0])
        for r in g[g.split != in_split].itertuples():
            rows.append(
                {
                    "exp": exp,
                    "test_set": r.split,
                    "in_dataset_auc": round(in_auc, 4),
                    "cross_dataset_auc": round(float(r.auc_mean), 4),
                    "gap": round(in_auc - float(r.auc_mean), 4),
                    "n_seeds": int(r.n_seeds),
                }
            )
    if not rows:
        # Normal early in the project: until a target test set has been
        # evaluated there is no gap to report. An empty frame with the right
        # columns keeps every caller's .empty check working.
        return pd.DataFrame(
            columns=["exp", "test_set", "in_dataset_auc", "cross_dataset_auc", "gap", "n_seeds"]
        )
    return pd.DataFrame(rows).sort_values("gap", ascending=False)


def _fmt(mean: float, std: float, places: int = 3) -> str:
    if not np.isfinite(mean):
        return "--"
    if not np.isfinite(std):
        return f"{mean:.{places}f}"
    return f"{mean:.{places}f} $\\pm$ {std:.{places}f}"


def to_latex(agg: pd.DataFrame, caption: str, label: str) -> str:
    """IEEE two-column table. Single-seed rows are marked in the caption."""
    if agg.empty:
        return "% no results to tabulate\n"

    lines = [
        "\\begin{table}[t]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Experiment & Test set & $N$ & AUC & Acc. & EER \\\\",
        "\\midrule",
    ]
    singles = []
    for r in agg.itertuples():
        mark = "$^{\\dagger}$" if r.single_seed else ""
        if r.single_seed:
            singles.append(f"{r.exp}/{r.split}")
        lines.append(
            f"{r.exp.replace('_', ' ')}{mark} & {r.split} & {int(r.n)} & "
            f"{_fmt(r.auc_mean, r.auc_std)} & "
            f"{_fmt(r.accuracy_mean, r.accuracy_std)} & "
            f"{_fmt(r.eer_mean, r.eer_std)} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    if singles:
        lines.append(
            "\\\\[2pt]\\footnotesize $^{\\dagger}$ single seed; all other rows "
            "are mean $\\pm$ std over 3 seeds."
        )
    lines.append("\\end{table}")
    return "\n".join(lines) + "\n"


def write_outputs(run_root: str, out_dir: str) -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    raw = collect_runs(run_root)
    written: dict[str, Path] = {}
    if raw.empty:
        return written

    raw.to_csv(out / "all_runs.csv", index=False)
    written["all_runs"] = out / "all_runs.csv"

    agg = aggregate_seeds(raw)
    agg.to_csv(out / "by_experiment.csv", index=False)
    written["by_experiment"] = out / "by_experiment.csv"

    (out / "table_main.tex").write_text(
        to_latex(
            agg,
            caption=(
                "Detection performance. In-dataset rows use the source validation "
                "split; cross-dataset rows use held-out forgery datasets with the "
                "decision threshold fixed on the source validation split."
            ),
            label="tab:main",
        )
    )
    written["table_main"] = out / "table_main.tex"

    gaps = cross_dataset_table(agg)
    if not gaps.empty:
        gaps.to_csv(out / "cross_dataset_gap.csv", index=False)
        written["gap"] = out / "cross_dataset_gap.csv"

    breakdowns = raw[raw.is_breakdown]
    if not breakdowns.empty:
        breakdowns.to_csv(out / "breakdowns.csv", index=False)
        written["breakdowns"] = out / "breakdowns.csv"

    # Warn about anything that would make a table misleading.
    bad_cal = raw[raw.calibration_degenerate == True]  # noqa: E712
    if not bad_cal.empty:
        log.warning(
            "%d run(s) have degenerate calibration; their ECE and calibrated "
            "probabilities must NOT be reported: %s",
            len(bad_cal),
            sorted(set(bad_cal.exp)),
        )
    dirty = raw[raw.git_sha.str.endswith("-dirty", na=False)]
    if not dirty.empty:
        log.warning(
            "%d run(s) were produced from a DIRTY working tree and are not reproducible: %s",
            len(dirty),
            sorted(set(dirty.exp)),
        )
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default="results")
    a = ap.parse_args(argv)
    setup_logging()

    written = write_outputs(a.runs, a.out)
    if not written:
        print("no results found. Train something, then `python -m ddetect.evaluate --run ...`")
        return 1

    raw = collect_runs(a.runs)
    agg = aggregate_seeds(raw)
    print("\n" + agg.to_string(index=False))

    gaps = cross_dataset_table(agg)
    if not gaps.empty:
        print("\nCROSS-DATASET GAP:")
        print(gaps.to_string(index=False))

    print("\nwrote:")
    for k, p in written.items():
        print(f"  {k:14s} {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
